// One-time: download Google Fonts (OFL) as woff2 and write fonts.css with base64 @font-face
// (Chrome blocks file:// font loads, so the fonts are inlined). usage: node fetch_fonts.mjs
import fs from "node:fs";
const FAMILIES = [
  "Sora:wght@500;600;700;800",
  "Anton",
  "Inter:wght@400;500;600;700;800",
  "Fraunces:opsz,wght@9..144,600;9..144,800;9..144,900",
  "JetBrains+Mono:wght@500;700",
  "Noto+Sans+Devanagari:wght@500;700;800",
];
const UA = { "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36" };
let out = "/* generated by fetch_fonts.mjs - Google Fonts, SIL OFL */\n";
for (const fam of FAMILIES) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${fam}&display=block`, { headers: UA })).text();
  const blocks = css.split("@font-face").slice(1);
  for (const b of blocks) {
    const sub = (b.match(/\/\*\s*([\w-]+)\s*\*\//) || [])[1];
    // keep only latin / latin-ext / devanagari subsets (comment precedes the block in the raw css)
    const url = (b.match(/url\((https:[^)]+\.woff2)\)/) || [])[1]; if (!url) continue;
    const buf = Buffer.from(await (await fetch(url, { headers: UA })).arrayBuffer());
    const body = b.replace(/src:[^;]+;/, `src: url(data:font/woff2;base64,${buf.toString("base64")}) format('woff2');`).replace(/\/\*[^*]*\*\//g, "");
    out += "@font-face" + body.trimEnd() + "\n";
  }
  console.log("ok", fam);
}
fs.writeFileSync("fonts/fonts.css", out); console.log("fonts/fonts.css", (out.length / 1e6).toFixed(1), "MB");
